// In-memory cache
const surahMemoryCache: Record<number, Ayah[]> = {};

/**
 * Fetch a complete Surah (all verses sequentially 1..N) with 100% diacritics integrity
 * from AlQuran Cloud multi-edition API:
 * - quran-uthmani (Arabic with diacritics)
 * - ur.jalandhry (Urdu translation)
 * - en.sahih (English translation)
 */
export async function getAyahsForSurah(surahNumber: number): Promise<Ayah[]> {
  // 1. Check in-memory cache
  if (surahMemoryCache[surahNumber] && surahMemoryCache[surahNumber].length > 0) {
    return surahMemoryCache[surahNumber];
  }

  // 2. Check localStorage cache
  try {
    const cached = localStorage.getItem(`quran_v3_surah_${surahNumber}`);
    if (cached) {
      const parsed = JSON.parse(cached) as Ayah[];
      if (parsed && parsed.length > 0) {
        surahMemoryCache[surahNumber] = parsed;
        return parsed;
      }
    }
  } catch (e) {
    console.warn("Storage cache read warning:", e);
  }

  // 3. Dynamic fetch from verified AlQuran Cloud API
  try {
    const res = await fetch(
      `https://api.alquran.cloud/v1/surah/${surahNumber}/editions/quran-uthmani,ur.jalandhry,en.sahih`
    );

    if (!res.ok) {
      throw new Error(`AlQuran Cloud API returned HTTP ${res.status}`);
    }

    const json = await res.json();
    if (!json.data || !Array.isArray(json.data) || json.data.length < 3) {
      throw new Error("Invalid API response format from AlQuran Cloud");
    }

    const uthmaniEdition = json.data.find((e: any) => e.edition.identifier === "quran-uthmani") || json.data[0];
    const urduEdition = json.data.find((e: any) => e.edition.identifier === "ur.jalandhry") || json.data[1];
    const englishEdition = json.data.find((e: any) => e.edition.identifier === "en.sahih") || json.data[2];

    const bismillahText = "بِسْمِ ٱللَّهِ ٱلرَّحْمَٰنِ ٱلرَّحِيمِ";

    const ayahs: Ayah[] = uthmaniEdition.ayahs.map((item: any, idx: number) => {
      let arabicText = item.text ? item.text.replace(/^\ufeff/, "").trim() : "";

      // For Surahs other than Al-Fatihah (Surah 1) and At-Tawbah (Surah 9),
      // the raw quran-uthmani database includes Bismillah at the head of Ayah 1.
      // We strip it so the verse text corresponds 100% with the verse number, Urdu, and English.
      // Bismillah is then rendered reverently as the Surah Bismillah header!
      if (surahNumber !== 1 && surahNumber !== 9 && item.numberInSurah === 1) {
        if (arabicText.startsWith(bismillahText)) {
          arabicText = arabicText.slice(bismillahText.length).trim();
        }
      }

      const urduAyah = urduEdition.ayahs ? urduEdition.ayahs[idx] : null;
      const englishAyah = englishEdition.ayahs ? englishEdition.ayahs[idx] : null;

      return {
        surahNumber,
        ayahNumber: item.numberInSurah,
        key: `${surahNumber}:${item.numberInSurah}`,
        textUthmani: arabicText,
        textIndoPak: arabicText, // Crisp standard Arabic
        translationUrdu: urduAyah ? urduAyah.text : "",
        translationEnglish: englishAyah ? englishAyah.text : "",
        audioUrl: `https://cdn.islamic.network/quran/audio/128/ar.alafasy/${item.number}.mp3`,
        juz: item.juz || 1,
      };
    });

    if (ayahs.length > 0) {
      surahMemoryCache[surahNumber] = ayahs;
      try {
        localStorage.setItem(`quran_v3_surah_${surahNumber}`, JSON.stringify(ayahs));
      } catch (e) {
        // LocalStorage may exceed quota for very large datasets, non-fatal
        console.warn("Storage cache write warning:", e);
      }
      return ayahs;
    }
  } catch (error) {
    console.error(`Failed to fetch Surah ${surahNumber} from AlQuran Cloud:`, error);
  }

  // 4. Fallback if offline and Surah 1 requested
  if (surahNumber === 1) {
    return VERIFIED_OFFLINE_AYAHS;
  }

  // Return empty array to let caller handle retry or offline state cleanly
  return [];
}

/**
 * Preload the next Surah into memory / localStorage in background
 */
export function preloadNextSurah(currentSurahNumber: number) {
  const next = currentSurahNumber + 1;
  if (next <= 114 && !surahMemoryCache[next]) {
    getAyahsForSurah(next).catch(() => {});
  }
}
